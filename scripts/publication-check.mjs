#!/usr/bin/env node
// Nothing personal and nothing naming a competitor goes into this public repository (docs/engineering.md, "What may
// be published"). This reads a pull request's title and description, every commit message in it, and every line it
// adds, and fails on:
//
// - a real tailnet: a `tail<hex>.ts.net` name or a `tail<hex>` id (`tail1234` and `example` are the placeholders);
// - a Tailscale address (100.64.0.0/10);
// - a home directory (`/Users/…`, `/home/<user>`) or a mounted volume (`/Volumes/…`) other than the placeholders
//   `/Users/dev`, `/Users/me`, `/home/runner`, `/home/dev`, `/home/user`, `/Volumes/dev`;
// - an email address other than example domains, the product's own domains and no-reply senders;
// - anything matching PUBLICATION_DENYLIST, one regular expression per line (case-insensitive unless it starts with
//   `=`), kept as a repository secret: the competitors' names and the owner's own machine names and addresses, which
//   this file must not spell out either.
//
//   node scripts/publication-check.mjs --range BASE..HEAD [--text-env TITLE --text-env BODY] [--require-denylist]
//
// --require-denylist fails when PUBLICATION_DENYLIST is empty: a pull request from this repository (and Dependabot's,
// which reads Dependabot secrets) must be checked against it. Forks get no secrets, so for them the workflow warns
// and a maintainer reads the pull request instead.
//
// The pull request workflow (.github/workflows/pull-request.yml) runs it.
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

/** Files that must spell out a pattern to test for it. */
const EXEMPT = new Set(["scripts/publication-check.mjs", "scripts/publication-check.test.mjs"]);
/** Generated by package managers from public registries (deprecation notices carry maintainers' addresses). */
const GENERATED = /(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml)$/;

const PLACEHOLDER_PATHS = /^\/(Users\/(dev|me)|home\/(runner|dev|user)|Volumes\/dev)\b/;
// Example and test domains, the product's own (its sender address and the dev accounts), GitHub's no-reply senders
// and the co-author trailer's.
const ALLOWED_EMAIL =
  /@(example\.(com|org|net)|[a-z0-9-]+\.(example|test|invalid)|bookanything\.(ie|test)|users\.noreply\.github\.com|anthropic\.com)$/i;

const RULES = [
  { why: "a real tailnet name", find: /\b[a-z0-9-]*\.?tail[0-9a-f]{4,}\.ts\.net\b/gi, allow: /\btail1234\.ts\.net$/i },
  { why: "a real tailnet id", find: /\btail[0-9a-f]{6}\b/gi, allow: /^tail1234$/i },
  { why: "a Tailscale address", find: /\b100\.(6[4-9]|[7-9]\d|1[01]\d|12[0-7])\.\d{1,3}\.\d{1,3}\b/g },
  {
    why: "a home directory or local volume",
    find: /\/Users\/[A-Za-z0-9._-]+|\/home\/[a-z][a-z0-9._-]*|\/Volumes\/[A-Za-z0-9._-]+/g,
    allow: PLACEHOLDER_PATHS,
  },
  { why: "an email address", find: /\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b/g, allow: ALLOWED_EMAIL },
];

/** Compiles PUBLICATION_DENYLIST: one expression per line, case-insensitive unless the line starts with `=`. */
export function denylist(text = "") {
  return text
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#"))
    .map((line) => (line.startsWith("=") ? new RegExp(line.slice(1), "g") : new RegExp(line, "gi")));
}

/** What in `text` must not be published. A denylisted match is reported without its text, so no log repeats it. */
export function findings(text, deny = []) {
  const found = [];
  for (const rule of RULES) {
    for (const match of text.matchAll(rule.find)) {
      if (rule.allow?.test(match[0])) continue;
      found.push(`${rule.why} (${match[0]})`);
    }
  }
  for (const pattern of deny) {
    pattern.lastIndex = 0;
    if (pattern.test(text)) found.push("a denylisted name (PUBLICATION_DENYLIST)");
  }
  return found;
}

function git(...args) {
  return execFileSync("git", args, { encoding: "utf8", maxBuffer: 1 << 30 });
}

/** The added lines of a unified diff (`git diff -U0`), with where each one is, skipping exempt and generated files. */
export function addedLines(diff) {
  const out = [];
  let file = null;
  let line = 0;
  for (const row of diff.split("\n")) {
    if (row.startsWith("+++ ")) {
      file = row === "+++ /dev/null" ? null : row.slice(6);
    } else if (row.startsWith("@@")) {
      line = Number(/\+(\d+)/.exec(row)?.[1] ?? 0);
    } else if (row.startsWith("+") && file) {
      if (!EXEMPT.has(file) && !GENERATED.test(file)) out.push({ where: `${file}:${line}`, text: row.slice(1) });
      line += 1;
    }
  }
  return out;
}

export function main(argv, { env = process.env, log = console.log, error = console.error } = {}) {
  const ranges = [];
  const texts = [];
  let requireDenylist = false;
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--range") ranges.push(argv[++i]);
    else if (argv[i] === "--text-env") texts.push(argv[++i]);
    else if (argv[i] === "--require-denylist") requireDenylist = true;
    else {
      error("usage: publication-check.mjs [--range BASE..HEAD] [--text-env NAME]... [--require-denylist]");
      return 2;
    }
  }
  const deny = denylist(env.PUBLICATION_DENYLIST);
  if (requireDenylist && !deny.length) {
    error("::error::PUBLICATION_DENYLIST is empty: add it as a repository secret, for Actions and for Dependabot (docs/engineering.md, \"What may be published\").");
    return 1;
  }
  const failures = [];
  const check = (where, text) => {
    for (const what of findings(text, deny)) failures.push(`${where}: ${what}`);
  };
  for (const name of texts) check(`pull request ${name.toLowerCase()}`, env[name] ?? "");
  for (const range of ranges) {
    // Merge commits too: their messages are published like any other.
    for (const entry of git("log", "--format=%h%x00%B%x1e", range).split("\x1e")) {
      const [sha, message] = entry.trim().split("\0");
      if (sha) check(`commit ${sha}`, message ?? "");
    }
    const [base, head] = range.split("..");
    const diff = git("diff", "-U0", "--no-color", "--no-ext-diff", `${base}...${head}`);
    for (const { where, text } of addedLines(diff)) check(where, text);
  }
  for (const failure of failures) error(`::error::${failure}`);
  if (failures.length) {
    error(`\n${failures.length} thing(s) that must not be published. See docs/engineering.md, "What may be published".`);
    return 1;
  }
  log(`Nothing personal or denylisted (${deny.length} denylist patterns).`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv.slice(2)));
}
